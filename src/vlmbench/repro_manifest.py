"""Generate the pinned-input table for the reproducibility manifest (audit item 6).

Rules, enforced in code rather than by convention:
- A model revision that is UNPINNED in the config is rendered as UNPINNED, never as a value.
- A dataset revision is never stored in the configs and is never resolved here (no network,
  no downloads). It is rendered as BLOCKED until an owner-approved commit SHA exists.
- A revision that is neither a token above nor a 40-hex commit is refused, and so is a
  placeholder-looking SHA (for example 40 zeros, or a single repeated character). A
  fabricated pin therefore cannot be rendered as a pinned value.

Usage: python -m vlmbench.repro_manifest --config configs/a100_qwen_priority_pilot.json \
           --out docs/audit/PINNED_INPUTS.md
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path

from .hf_sources import DATASETS

UNPINNED = "UNPINNED"
BLOCKED = "BLOCKED"
PINNED = "PINNED"
UNPINNED_TOKENS = frozenset({UNPINNED, "", "REPLACE"})
COMMIT_SHA = re.compile(r"[0-9a-f]{40}")


class PinError(ValueError):
    pass


def _looks_like_placeholder(sha: str) -> bool:
    # A real 40-hex commit has about 16 distinct characters. Fewer than 6 means a
    # placeholder (for example "0"*40, "a"*40, "abab...").
    return len(set(sha)) < 6


def classify_revision(value: object) -> tuple[str, str]:
    """Return (status, rendered) for a model revision from the config."""
    if value is None or (isinstance(value, str) and value in UNPINNED_TOKENS):
        return UNPINNED, UNPINNED
    if not isinstance(value, str) or not COMMIT_SHA.fullmatch(value):
        raise PinError(f"revision {value!r} is neither UNPINNED nor a 40-hex commit SHA")
    if _looks_like_placeholder(value):
        raise PinError(f"revision {value!r} looks like a placeholder; refusing to render it as pinned")
    return PINNED, value


def model_rows(cfg: dict) -> list[dict]:
    rows = []
    for model in cfg["models"]:
        status, rendered = classify_revision(model.get("revision"))
        rows.append({"input": f"model revision: {model['hf_id']}", "config_id": model["id"],
                     "status": status, "value": rendered,
                     "required": "owner-approved commit SHA written to .hf_source.json and models[].revision"})
    return rows


def dataset_rows(datasets: dict | None = None) -> list[dict]:
    """Dataset revisions are BLOCKED: they are absent from the configs and unresolved here."""
    rows = []
    for dataset_id, repo in sorted((datasets or DATASETS).items()):
        rows.append({"input": f"dataset revision: {repo}", "config_id": dataset_id,
                     "status": BLOCKED, "value": BLOCKED,
                     "required": "owner-approved commit SHA; not present in configs; "
                                  "resolved only by an authorised fetch"})
    return rows


def pin_rows(cfg: dict, datasets: dict | None = None) -> list[dict]:
    return model_rows(cfg) + dataset_rows(datasets)


def render_markdown(cfg_name: str, cfg_sha256: str, rows: list[dict]) -> str:
    lines = [
        "# Pinned inputs (generated)",
        "",
        "Generated by `python -m vlmbench.repro_manifest`. Do not edit by hand: "
        "`tests/test_repro_manifest.py` regenerates this file and fails on any drift.",
        "",
        f"Source config: `{cfg_name}` (SHA-256 `{cfg_sha256}`).",
        "",
        "Status meanings: **PINNED** = commit SHA present in the config. "
        "**UNPINNED** = the config carries no revision (the run cannot start). "
        "**BLOCKED** = not in the config and not resolvable here; needs owner approval.",
        "",
        "| Input | Config id | Status | Value | What is required before a paid run |",
        "|---|---|---|---|---|",
    ]
    for row in rows:
        lines.append(f"| {row['input']} | `{row['config_id']}` | {row['status']} | "
                     f"`{row['value']}` | {row['required']} |")
    lines.append("")
    return "\n".join(lines)


def generate(config_path: Path) -> tuple[str, list[dict]]:
    raw = Path(config_path).read_bytes()
    cfg = json.loads(raw)
    rows = pin_rows(cfg)
    return render_markdown(Path(config_path).name, hashlib.sha256(raw).hexdigest(), rows), rows


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="vlmbench.repro_manifest")
    parser.add_argument("--config", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args(argv)
    text, _ = generate(args.config)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
